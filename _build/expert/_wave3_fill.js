const pages = [...new Set(Object.keys(T).map(id => id.replace(/_\d+$/, '').replace(/_/g, '-')))];

let added = 0, kept = 0;
for (const page of pages) {
  const batchPath = path.join(BATCHES, page + '.json');
  const workPath = path.join(__dirname, 'work', page + '.json');
  const batch = JSON.parse(fs.readFileSync(batchPath, 'utf8'));
  const work = JSON.parse(fs.readFileSync(workPath, 'utf8'));
  for (const w of work) {
    if (typeof batch[w.hash] === 'string' && batch[w.hash].trim()) { kept++; continue; }
    const paras = T[w.id];
    if (!paras) continue;
    batch[w.hash] = paras.join('\n\n');
    added++;
  }
  fs.writeFileSync(batchPath, JSON.stringify(batch, null, 1), 'utf8');
}
console.log('added', added, '| kept existing', kept);
