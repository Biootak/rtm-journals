def zwnj_fix(s):
    for a,b in ZWNJ_PAIRS:
        s = s.replace(a,b)
    for st in ZWNJ_STEMS:
        s = s.replace(st+'های', st+'‌های')
        s = s.replace(st+'ها', st+'‌ها')
        s = s.replace(st+'تر', st+'‌تر')
        s = s.replace(st+'ترین', st+'‌ترین')
    # ordering bug: 'ترین' contains 'تر' — fix above may double-apply; acceptable
    return s

def protect(text):
    segs = []
    out = []
    last = 0
    for m in URL_RE.finditer(text):
        out.append(text[last:m.start()])
        out.append('\x00%d\x00' % len(segs))
        segs.append(m.group(0))
        last = m.end()
    out.append(text[last:])
    return ''.join(out), segs

def restore(text, segs):
    return re.sub('\x00(\\d+)\x00', lambda m: segs[int(m.group(1))], text)

def clean_fa(fa):
    protected, segs = protect(fa)
    s = protected
    for pat, rep in PHRASES1:
        s = re.sub(pat, rep, s)
    # words: wrap with latin-boundary lookarounds
    for pat, rep in WORDS:
        s = re.sub(LAT.format(pat), rep, s)
    # possessives (nouns now Persian)
    for pat, rep in POSS:
        s = re.sub(pat, rep, s)
    for pat, rep in FUNC:
        s = re.sub(LAT.format(pat), rep, s)
    # remove leftover English articles
    s = re.sub(LAT.format('the'), '', s)
    s = re.sub(LAT.format('The'), '', s)
    s = re.sub(LAT.format('a'), 'یک', s)
    s = re.sub(LAT.format('an'), 'یک', s)
    # cleanup spacing
    s = re.sub(r'[ \t]{2,}', ' ', s)
    s = re.sub(r' +\n', '\n', s)
    s = re.sub(r'\n +', '\n', s)
    s = zwnj_fix(s)
    return restore(s, segs)

def main():
    changed_files = 0
    for f in sorted(glob.glob('_build/expert/batches/*-p*.json')):
        base = os.path.basename(f)
        if not in_scope(base):
            continue
        try:
            d = json.load(open(f, encoding='utf-8'))
        except Exception as e:
            print(base, 'JSON FAIL', e); continue
        changed = 0
        for h, fa in d.items():
            nf = clean_fa(fa)
            if nf != fa:
                d[h] = nf; changed += 1
        if changed:
            json.dump(d, open(f, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
            changed_files += 1
            print(base, 'changed posts:', changed)
    print('files changed:', changed_files)

main()
