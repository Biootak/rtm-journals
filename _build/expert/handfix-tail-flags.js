for (const [page, map] of Object.entries(PAGES)) {
  const W = path.join(__dirname, 'work', page + '.json');
  const B = path.join(__dirname, 'batches', page + '.json');
  const work = JSON.parse(fs.readFileSync(W, 'utf8'));
  const batch = JSON.parse(fs.readFileSync(B, 'utf8'));
  let n = 0;
  for (const post of work) {
    const ps = map[post.id];
    if (!ps) continue;
    const en = post.text.split(/\n{2,}/).filter(x => x.trim()).length;
    if (ps.length !== en) throw new Error(`${post.id}: ${ps.length} FA vs ${en} EN`);
    batch[post.hash] = ps.join('\n\n');
    n++;
  }
  if (n !== Object.keys(map).length) throw new Error(`${page}: ${n}/${Object.keys(map).length}`);
  fs.writeFileSync(B, JSON.stringify(batch), 'utf8');
  console.log(`${page}: rewrote ${n} post(s)`);
}
